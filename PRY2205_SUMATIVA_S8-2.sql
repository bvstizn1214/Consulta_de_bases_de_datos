CREATE OR REPLACE VIEW VW_DETALLE_MULTAS AS
SELECT
  p.prestamoid                                                   AS ID_PRESTAMO,

  RTRIM(
    NVL(a.nombre,'') || ' ' ||
    NVL(a.apaterno,'') || ' ' ||
    NVL(a.amaterno,'')
  )                                                              AS NOMBRE_ALUMNO,

  -- Nombre de la carrera
  NVL(c.descripcion, 'SIN CARRERA')                              AS NOMBRE_CARRERA,

  l.libroid                                                      AS ID_LIBRO,

  ROUND(NVL(l.precio,0), 0)                                      AS VALOR_LIBRO,

  TRUNC(p.fecha_termino)                                         AS FECHA_TERMINO,
  TRUNC(p.fecha_entrega)                                         AS FECHA_ENTREGA,

  (TRUNC(p.fecha_entrega) - TRUNC(p.fecha_termino))              AS DIAS_ATRASO,

  -- Multa: 3% del precio por día de atraso (entero)
  ROUND(
    NVL(l.precio,0) * 0.03 *
    (TRUNC(p.fecha_entrega) - TRUNC(p.fecha_termino)),
    0
  )                                                              AS VALOR_MULTA,

  NVL(mr.porc_rebaja_multa, 0)                                   AS PORCENTAJE_REBAJA_MULTA,

  -- Valor rebajado (entero)
  ROUND(
    ( NVL(l.precio,0) * 0.03 *
      (TRUNC(p.fecha_entrega) - TRUNC(p.fecha_termino))
    ) * NVL(mr.porc_rebaja_multa,0) / 100,
    0
  )                                                              AS VALOR_REBAJADO,

  -- Valor final a pagar (entero)
  ROUND(
    ( NVL(l.precio,0) * 0.03 *
      (TRUNC(p.fecha_entrega) - TRUNC(p.fecha_termino))
    ) * (1 - NVL(mr.porc_rebaja_multa,0) / 100),
    0
  )                                                              AS VALOR_A_PAGAR

FROM SYN_PRESTAMO p
JOIN SYN_ALUMNO   a ON p.alumnoid = a.alumnoid
JOIN SYN_LIBRO    l ON p.libroid  = l.libroid
LEFT JOIN CARRERA c ON a.carreraid = c.carreraid
LEFT JOIN MULTA_REBAJA mr ON a.carreraid = mr.carreraid

WHERE
  EXTRACT(YEAR FROM p.fecha_termino) =
  EXTRACT(YEAR FROM ADD_MONTHS(SYSDATE, -24))
  AND p.fecha_termino < p.fecha_entrega;


SELECT
  ID_PRESTAMO,
  NOMBRE_ALUMNO,
  NOMBRE_CARRERA,
  ID_LIBRO,
  VALOR_LIBRO,
  FECHA_TERMINO,
  FECHA_ENTREGA,
  DIAS_ATRASO,
  VALOR_MULTA,
  PORCENTAJE_REBAJA_MULTA,
  VALOR_REBAJADO,
  VALOR_A_PAGAR
FROM VW_DETALLE_MULTAS
ORDER BY FECHA_ENTREGA DESC
FETCH FIRST 20 ROWS ONLY;

