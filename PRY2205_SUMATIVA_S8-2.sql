DROP TABLE CONTROL_STOCK_LIBROS;

CREATE TABLE CONTROL_STOCK_LIBROS AS
SELECT
  ROW_NUMBER() OVER (ORDER BY l.libroid) AS ID_CONTROL,
  l.libroid AS LIBRO_ID,
  l.nombre_libro AS NOMBRE_LIBRO,
  NVL(ej.TOTAL_EJEMPLARES, 0) AS TOTAL_EJEMPLARES,
  NVL(pagg.EN_PRESTAMO, 0) AS EN_PRESTAMO,
  NVL(ej.TOTAL_EJEMPLARES, 0) - NVL(pagg.EN_PRESTAMO, 0) AS DISPONIBLES,
  ROUND(
    CASE
      WHEN NVL(ej.TOTAL_EJEMPLARES, 0) = 0 THEN 0
      ELSE (NVL(pagg.EN_PRESTAMO, 0) / NVL(ej.TOTAL_EJEMPLARES, 0)) * 100
    END, 0) AS PORCENTAJE_PRESTAMO,
  CASE
    WHEN (NVL(ej.TOTAL_EJEMPLARES, 0) - NVL(pagg.EN_PRESTAMO, 0)) > 2 THEN 'S'
    ELSE 'N'
  END AS STOCK_CRITICO,
  -- Mes y año del proceso
  TO_CHAR(ADD_MONTHS(TRUNC(SYSDATE,'MM'), -24),'MM') AS MES_PROCESO,
  TO_CHAR(ADD_MONTHS(TRUNC(SYSDATE,'MM'), -24),'YYYY') AS ANIO_PROCESO
FROM syn_libro l
LEFT JOIN (
  SELECT libroid, COUNT(*) AS TOTAL_EJEMPLARES
  FROM syn_ejemplar
  GROUP BY libroid
) ej ON ej.libroid = l.libroid
LEFT JOIN (
  -- EN_PRESTAMO: número de préstamos registrados en el mes procesado por empleados 150,180,190
  SELECT libroid, COUNT(*) AS EN_PRESTAMO
  FROM syn_prestamo
  WHERE empleadoid IN (150, 180, 190)
    AND fecha_inicio BETWEEN
      ADD_MONTHS(TRUNC(SYSDATE,'MM'), -24)
      AND LAST_DAY(ADD_MONTHS(TRUNC(SYSDATE,'MM'), -24))
  GROUP BY libroid
) pagg ON pagg.libroid = l.libroid
ORDER BY l.libroid
;

-- Agregar constraints
ALTER TABLE CONTROL_STOCK_LIBROS ADD CONSTRAINT PK_CONTROL_STOCK PRIMARY KEY (ID_CONTROL);
ALTER TABLE CONTROL_STOCK_LIBROS ADD CONSTRAINT CHK_DISPONIBLES_POS CHECK (DISPONIBLES >= 0);

-- Crear secuencia
DECLARE
  v_max NUMBER;
BEGIN
  SELECT NVL(MAX(ID_CONTROL), 0) INTO v_max FROM CONTROL_STOCK_LIBROS;
  EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_CONTROL_STOCK START WITH ' || TO_CHAR(v_max + 1) || ' INCREMENT BY 1 NOCACHE NOCYCLE';
EXCEPTION WHEN OTHERS THEN
  NULL;
END;
/

-- Trigger para asignar ID_CONTROL usando la secuencia en INSERT posteriores
CREATE OR REPLACE TRIGGER TRG_CTRLSTK_BI
BEFORE INSERT ON CONTROL_STOCK_LIBROS
FOR EACH ROW
BEGIN
  IF :NEW.ID_CONTROL IS NULL THEN
    SELECT SEQ_CONTROL_STOCK.NEXTVAL INTO :NEW.ID_CONTROL FROM DUAL;
  END IF;
END;
/

-- Índices para optimizar consultas
CREATE INDEX IDX_CTRLSTK_LIBROID ON CONTROL_STOCK_LIBROS(LIBRO_ID);
CREATE INDEX IDX_CTRLSTK_STOCK_CRITICO ON CONTROL_STOCK_LIBROS(STOCK_CRITICO);
CREATE INDEX IDX_CTRLSTK_PORCENTAJE ON CONTROL_STOCK_LIBROS(PORCENTAJE_PRESTAMO DESC);

